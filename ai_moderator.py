# ai_moderator.py

import logging
import json
import io
from PIL import Image 
import google.generativeai as genai
from config import GOOGLE_API_KEY

# 1. Настройка
genai.configure(api_key=GOOGLE_API_KEY)

# 2. СИСТЕМНЫЕ ПРАВИЛА (МОЗГ БОТА)
SYSTEM_PROMPT = """
Ты — строгий модератор доски объявлений в Telegram "Базар Варшава".
Твоя задача: проанализировать текст, фото и категорию на соответствие правилам.

ГЛОБАЛЬНЫЕ ПРАВИЛА:

1. БЕЗОПАСНОСТЬ (REJECT): 
   - Наркотики, боевое оружие, проституция, интим-услуги, мошенничество, спам.
   - Лекарства, таблетки, инъекции (включая ветеринарные).
   - Жидкости для вейпов с никотином, алкоголь, табак, сигареты.
   - ИСКЛЮЧЕНИЯ (APPROVE): Спортивное питание, детское питание, БАДы (если это не лекарства), легальный спорт-инвентарь (пневматика, ножи).

2. ЦИФРОВЫЕ ТОВАРЫ И УСЛУГИ (СТРОГИЙ ЗАПРЕТ): 
   - Раздел "Продать" предназначен ТОЛЬКО для физических товаров.
   - Любые УСЛУГИ (ремонт, перевозки, няня, "ищу работу") -> REJECT.
   - Цифровые товары (аккаунты, ключи, подписки, курсы) -> REJECT.
   - Причина отказа: "Реклама услуг и цифровых товаров платная. Информацию о рекламе ищите в главном меню."

3. КОММЕРЧЕСКАЯ ДЕЯТЕЛЬНОСТЬ:
   - Объявление должно быть от частного лица.
   - РАЗРЕШЕНО: продажа личных вещей, в том числе комплектов (например: 4 колеса, 2 джойстика, сервиз, набор инструментов).
   - ЗАПРЕЩЕНО (REJECT): признаки магазина, "ростовки" (размеры 36-45 в наличии), оптовая продажа (ящики товара), ссылки на магазины/каналы, "под заказ".
   - Причина отказа: "Коммерческая деятельность. Информацию о рекламе ищите в главном меню."

4. ГИГИЕНА И КОСМЕТИКА:
   - ЗАПРЕЩЕНО: б/у нательное белье (трусы), б/у купальники.
   - ЗАПРЕЩЕНО: б/у косметика (открытые кремы, тушь, помада).
   - РАЗРЕШЕНО: НОВАЯ косметика, парфюмерия (даже открытая), б/у верхняя одежда, открытые пачки подгузников.

5. ПРОДУКТЫ ПИТАНИЯ:
   - РАЗРЕШЕНО: Продукты в заводской упаковке (не вскрытые, не просроченные).
   - ЗАПРЕЩЕНО: Домашняя еда, скоропортящиеся открытые продукты.

6. ФОТО И РЕАЛЬНОСТЬ:
   - Фото экрана другого устройства (скриншоты) -> REJECT.
   - Если категория "Авто", а на фото телефон с машиной на заставке -> REJECT.

7. ТЕКСТ:
   - Бессмысленный набор букв ("asdfg") -> REJECT.

Верни ответ ТОЛЬКО в формате JSON:
{
    "decision": "approve" или "reject" или "manual",
    "reason": "Краткая причина решения на русском языке."
}
"""

model = genai.GenerativeModel(
    model_name="gemini-2.0-flash-live",
    system_instruction=SYSTEM_PROMPT,
    generation_config={"response_mime_type": "application/json"} 
)

async def moderate_ad_with_ai(bot, ad_data: dict) -> dict:
    description = ad_data.get('description', 'Нет описания')
    cat_code = ad_data.get('category', 'Не указана')
    
    # ОПИСАНИЕ КАТЕГОРИЙ
    CAT_NAMES = {
        "auto": "Автомобили, мотоциклы, запчасти, шины, диски, автохимия, аксессуары.",
        "bicycle": "Велосипеды, самокаты, гироскутеры, экипировка, запчасти и аксессуары к ним.",
        "phones": "Смартфоны, телефоны, чехлы, зарядки, кабеля, повербанки. (Опт запрещен).",
        "computers": "Компьютеры, ноутбуки, комплектующие, периферия, аксессуары.",
        "consoles": "Игровые консоли, физические диски с играми, геймпады. (Цифровые аккаунты запрещены).",
        "electronics": "Любая бытовая, кухонная, офисная, климатическая, фото/видео техника, вейпы (без никотина).",
        "home": "Мебель, декор, стройматериалы, инструменты, текстиль (б/у постельное/матрасы ОК), посуда. Всё для сада/двора.",
        "animals": "Животные (частная продажа), корм, клетки, игрушки, аксессуары.",
        "sport": "Только спорт-инвентарь, тренажеры, экипировка, туризм, рыбалка. (Спортпит и пневматика ОК).",
        "men_clothes": "Мужская одежда, обувь, аксессуары. (Реплики ОК, если указано. Б/у трусы/плавки запрещены).",
        "women_clothes": "Женская одежда, обувь, аксессуары, парфюмерия, косметика (только новая).",
        "kids": "ВСЁ, что связано с детьми: одежда, игрушки, транспорт, мебель, питание, гигиена.",
        "other": "Всё легальное, что не подошло выше: продукты питания (упакованные), книги, музыкальные инструменты, настольные игры, хобби, билеты."
    }
    
    category_desc = CAT_NAMES.get(cat_code, cat_code)
    ad_type = ad_data.get('ad_type', 'sell')
    photo_ids = ad_data.get('photos', [])

    user_prompt = f"""
    Выбранная категория (что в неё входит): {category_desc}
    Тип объявления: {ad_type}
    Описание пользователя: {description}
    """
    
    content_parts = [user_prompt] 

    if photo_ids:
        try:
            first_photo_id = photo_ids[0]
            file = await bot.get_file(first_photo_id)
            file_bytes = io.BytesIO()
            await bot.download_file(file.file_path, file_bytes)
            image = Image.open(file_bytes)
            content_parts.append(image)
        except Exception as e:
            logging.error(f"AI: Не удалось загрузить фото: {e}")

    try:
        logging.info("⏳ Отправка запроса к Gemini...")
        response = await model.generate_content_async(content_parts)
        result_json = json.loads(response.text)
        logging.info(f"🤖 AI Вердикт: {result_json}")
        return result_json

    except Exception as e:
        logging.error(f"AI Error: {e}")
        return {"decision": "manual", "reason": "Ошибка подключения к ИИ"}